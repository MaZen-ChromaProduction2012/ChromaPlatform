import re

class SmartAIAgent:
    """
    عقل الشات الذكي لمنصة ChromaProduction
    يقوم بالرد على استفسارات العملاء وأخذ تفاصيل المونتاج وإرشادهم
    """
    def __init__(self):
        self.system_prompt = "مساعد ChromaProduction الذكي للمونتاج والتصميم"

    def process_message(self, user_text):
        text = user_text.lower().strip()

        if any(w in text for w in ['سعر', 'كام', 'اسعار', 'تكلفة', 'بكام']):
            return ("أهلاً بك! أسعارنا بتعتمد على نوع ومدة الفيديو (ريلز سريعة، يوتيوب، إعلان تجاري). "
                    "تقدر تسجل طلبك وترفع الماتريال وهيتم تحديد التكلفة الدقيقة، أو تتواصل مع مازن عمرو مباشرة عبر واتساب: "
                    "https://wa.me/message/XP5IUCB56QUFH1")

        if any(w in text for w in ['وقت', 'هياخد اد ايه', 'مدة', 'هتخلصوا امتى']):
            return ("المونتاج السريع للريلز بياخد عادة من 24 لـ 48 ساعة. الفيديوهات الطويلة والإعلانات بتاخد من يومين لـ 4 أيام حسب الموشن جرافيك وتصحيح الألوان المطلوب.")

        if any(w in text for w in ['برامج', 'بتشتغلوا بايه', 'مونتاج بايه']):
            return "فريق ChromaProduction بيعتمد على أحدث حزم المونتاج الاحترافية: Adobe Premiere Pro, After Effects, DaVinci Resolve Studio لضبط الألوان بجودة السينما."

        if any(w in text for w in ['رفع', 'ماتريال', 'فيديو كبير', 'درايف']):
            return "تقدر ترفع الماتريال لحد 250 ميجا مباشرة من لوحة التحكم، ولو حجم الملفات أكبر تقدر تحط لينك Google Drive أو WeTransfer في وصف الطلب."

        return ("أهلاً بك في ChromaProduction! أنا مساعدك الذكي لمتابعة مشاريع المونتاج. "
                "تقدر تسألني عن الخدمات، أو ترفع طلبك في ثواني ليتم توزيعه على فريق المونتاج.")
